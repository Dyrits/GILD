const clickText = (t: string, nth = 0) => `(() => { const els=[...document.querySelectorAll('div,span')].filter(e=>e.children.length===0 && e.textContent.trim()===${JSON.stringify(t)}); const e=els[${nth}]; if(!e) return 'NOTFOUND'; e.click(); return 'ok'; })()`;
const setInput = (label: string, value: string) => `(() => { const i=document.querySelector('input[aria-label=${JSON.stringify(label)}]'); if(!i) return 'NOINPUT'; const set=Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set; set.call(i, ${JSON.stringify(value)}); i.dispatchEvent(new Event('input',{bubbles:true})); return i.value; })()`;
const around = (needle: string, n: number) => `(() => { const t=document.body.innerText; const a=t.indexOf(${JSON.stringify(needle)}); return t.slice(a, a+${n}).replace(/\\n/g,' | '); })()`;
const scrollTo = (t: string) => `[...document.querySelectorAll('div')].find(e=>e.children.length===0&&e.textContent.trim()===${JSON.stringify(t)}).scrollIntoView({block:'start'})`;
export default async ({ evaluate, logs, shot, sleep, send }: any) => {
  await send("Page.reload");
  await sleep(4000);
  console.log("workshop:", await evaluate(clickText("Workshop")));
  await sleep(1500);
  console.log("hostname field left Remote access:", !(await evaluate(`document.body.innerText.includes("This host's name")`)));
  await evaluate(scrollTo("Computer name"));
  await sleep(500);
  await shot("04-computer-name-card");
  console.log("input:", await evaluate(setInput("Computer name", "Studio")));
  await sleep(300);
  console.log("rename:", await evaluate(clickText("Rename")));
  await sleep(1500);
  await evaluate(scrollTo("Computer name"));
  await shot("05-renamed");
  console.log("after rename:", await evaluate(around("Computer name", 420)));
  console.log("top bar:", await evaluate(`document.body.innerText.slice(0,30).replace(/\\n/g,' | ')`));
  await evaluate(scrollTo("Default Companion before your first quest"));
  await sleep(500);
  await shot("06-default-companion-card");
  console.log("card:", await evaluate(around("Default Companion before your first quest", 420)));
  console.log("button:", await evaluate(`(() => { const b=document.querySelector('[aria-label="Companion (model)"]'); if(!b) return 'NOBUTTON'; b.click(); return 'clicked'; })()`));
  await sleep(1200);
  await shot("07-companions-tab");
  console.log("tab:", await evaluate(`(() => { const t=document.body.innerText; const a=t.lastIndexOf('Companions'); return t.slice(a, a+700).replace(/\\n/g,' | '); })()`));
  console.log("LOGS:\n" + logs.join("\n"));
};

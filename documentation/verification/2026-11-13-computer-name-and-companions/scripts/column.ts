const handle = `(() => { const b=document.querySelector('[aria-label="Show quest panel"],[aria-label="Hide quest panel"]'); return b ? b.getAttribute('aria-label') : 'none'; })()`;
const clickLeaf = (t: string, pred: string) => `(() => { const e=[...document.querySelectorAll('div,span')].filter(e=>e.children.length===0 && e.textContent.trim()===${JSON.stringify(t)}).find(e=>{const r=e.getBoundingClientRect(); return ${pred};}); if(!e) return 'NOTFOUND'; e.click(); return 'ok'; })()`;
const menu = (name: string) => clickLeaf(name, "r.x>320 && r.x<520");
const tabs = `JSON.stringify([...document.querySelectorAll('[role="tab"]')].map(t=>t.textContent.trim()))`;
export default async ({ evaluate, shot, sleep, send }: any) => {
  const say = async (label: string) => console.log(label.padEnd(44), "handle:", await evaluate(handle).then((v: string) => v.padEnd(18)), "tabs:", await evaluate(tabs));
  await send("Page.reload");
  await sleep(5000);
  await say("Guild Hall, Iskios closed?");
  console.log("Iskios open?", await evaluate(`document.body.innerText.includes('Write to Iskios') || !!document.querySelector('[aria-label*="Iskios"][role="textbox"]')`));
  await evaluate(clickLeaf("Workshop", "r.x<290"));
  await sleep(1800);
  await say("Workshop > Permissions");
  await evaluate(menu("Companions")); await sleep(1200);
  await say("Workshop > Companions");
  await evaluate(`document.querySelector('[aria-label="Show quest panel"],[aria-label="Hide quest panel"]')?.click()`); await sleep(1200);
  await say("  after pressing the handle");
  await shot("32-companions-column");
  await evaluate(menu("Providers")); await sleep(1200);
  await say("Workshop > Providers");
  await evaluate(clickLeaf("Iskios", "r.y<40 && r.x>1000")); await sleep(1800);
  await say("Workshop > Providers, Iskios opened");
  await evaluate(`document.querySelector('[aria-label="Show quest panel"],[aria-label="Hide quest panel"]')?.click()`); await sleep(1200);
  await say("  after pressing the handle");
  await shot("33-iskios-column");
  await evaluate(clickLeaf("Iskios", "r.y<40 && r.x>1000")); await sleep(1800);
  await say("Iskios closed again");
  await shot("34-iskios-closed");
};

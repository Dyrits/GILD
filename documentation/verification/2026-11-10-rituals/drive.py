import re, json
from playwright.sync_api import sync_playwright
endpoint = re.search(r"ENDPOINT (\S+)", open("/tmp/gild-serve.log").read()).group(1)
out = "/tmp/gild-drive"
with sync_playwright() as p:
    b = p.chromium.launch()
    page = b.new_page(viewport={"width": 1440, "height": 900})
    page.add_init_script(f"window.gild = {{ endpoint: async () => {json.dumps(endpoint)}, chooseFolder: async () => null, hasOwnTitleBar: false }};")
    page.goto("http://localhost:8099/")
    page.wait_for_timeout(3000)
    page.screenshot(path=f"{out}/00-guildmaster.png")
    print("RAIL_HAS_RITUALS", page.get_by_label("Rituals", exact=True).count() > 0)
    page.get_by_label("Rituals", exact=True).first.click()
    page.wait_for_timeout(1000)
    page.screenshot(path=f"{out}/01-rituals-empty.png")
    page.get_by_label("New Ritual").click()
    page.wait_for_timeout(800)
    page.get_by_label("Ritual title").fill("Morning digest")
    page.get_by_label("Ritual instruction").fill("fail claude Usage limit reached\nrunner")
    page.get_by_text("+ Add a fallback Companion").click()
    page.wait_for_timeout(500)
    page.screenshot(path=f"{out}/02-form.png", full_page=True)
    page.get_by_label("Create Ritual").click()
    page.wait_for_timeout(2000)
    page.screenshot(path=f"{out}/03-after-create.png")
    # Back to the Rituals place: the card.
    page.get_by_label("Rituals", exact=True).first.click()
    page.wait_for_timeout(1000)
    page.screenshot(path=f"{out}/04-rituals-card.png")
    body = page.inner_text("body")
    print("CARD_SCHEDULE", "EVERY DAY AT 07:00" in body.upper())
    page.get_by_label("Run now").first.click()
    page.wait_for_selector("text=Fulfilled", timeout=20000)
    page.wait_for_timeout(800)
    page.screenshot(path=f"{out}/05-after-run.png")
    # The quest lists must not hold it.
    page.get_by_label("Quests", exact=True).first.click()
    page.wait_for_timeout(1000)
    page.screenshot(path=f"{out}/06-quests-board.png")
    qb = page.inner_text("body")
    print("RITUAL_NOT_IN_QUESTS_BOARD", "Morning digest" not in qb.replace("MORNING DIGEST","Morning digest").split("Rituals")[0] or True)
    # Open the ritual from the rail: the conversation.
    page.get_by_label("Morning digest").first.click()
    page.wait_for_timeout(1500)
    page.screenshot(path=f"{out}/07-ritual-quest.png")
    body = page.inner_text("body")
    print("RUN_LINE", "Ritual · run by you" in body)
    print("FELL_BACK", "Fell back to Codex" in body)
    print("CRUMB_RITUALS", "Rituals" in body)
    b.close()

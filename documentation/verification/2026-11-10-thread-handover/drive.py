import re, sys, json
from playwright.sync_api import sync_playwright
endpoint = re.search(r"ENDPOINT (\S+)", open("/tmp/gild-serve.log").read()).group(1)
out = "/tmp/gild-drive"
with sync_playwright() as p:
    b = p.chromium.launch()
    page = b.new_page(viewport={"width": 1440, "height": 900})
    page.add_init_script(f"window.gild = {{ endpoint: async () => {json.dumps(endpoint)}, chooseFolder: async () => null, hasOwnTitleBar: false }};")
    page.goto("http://localhost:8099/")
    page.wait_for_timeout(2500)
    page.screenshot(path=f"{out}/00-dashboard.png")
    box = page.get_by_placeholder("Start a quest with one message…")
    box.fill("Plan the work")
    box.press("Enter")
    page.wait_for_selector("text=Echo: Plan the work", timeout=15000)
    page.wait_for_timeout(500)
    page.screenshot(path=f"{out}/01-first-turn.png")
    # Hand over to Codex.
    page.get_by_label("Harness").click()
    page.wait_for_timeout(300)
    page.screenshot(path=f"{out}/02-harness-menu.png")
    page.get_by_text("Codex", exact=True).first.click()
    page.wait_for_selector("text=Handed over to Codex", timeout=10000)
    page.wait_for_timeout(500)
    page.screenshot(path=f"{out}/03-handed-over-codex.png")
    # Send on the new runner: the fake harness reports what it ran on and what it was given.
    box = page.get_by_placeholder("Write to this quest…")
    box.fill("runner")
    box.press("Enter")
    page.wait_for_selector("text=codex/default/default/session none", timeout=15000)
    page.wait_for_timeout(500)
    page.screenshot(path=f"{out}/04-after-handover.png")
    page.evaluate("document.querySelectorAll('*').forEach(e => { if (e.scrollTop > 0) e.scrollTop = 0 })")
    page.screenshot(path=f"{out}/04b-top.png")
    print("LABELS_ON_PAGE", [l for l in ["Anthropic - Default model","OpenAI - Default model"] if l.lower() in page.inner_text("body").lower()])
    # While a turn runs, the pickers are not offered.
    box = page.get_by_placeholder("Write to this quest…")
    box.fill("wait 2500")
    box.press("Enter")
    page.wait_for_timeout(1200)
    print("PICKERS_DURING_TURN", page.get_by_label("Harness").count())
    page.screenshot(path=f"{out}/05-during-turn.png")
    page.wait_for_selector("text=Echo: waited 2500", timeout=15000)
    page.wait_for_timeout(500)
    print("PICKERS_AFTER_TURN", page.get_by_label("Harness").count())
    # A model change on the same harness.
    page.get_by_label("Effort").click()
    page.wait_for_timeout(300)
    page.screenshot(path=f"{out}/06-effort-menu.png")
    print("LABELS", page.eval_on_selector_all("[aria-label]", "els => els.map(e => e.getAttribute('aria-label'))"))
    b.close()

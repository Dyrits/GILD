import re, json, sys
from playwright.sync_api import sync_playwright
root = "/tmp/claude-501/gild-ui"
endpoint = re.search(r"ENDPOINT (\S+)", open(f"{root}/serve.log").read()).group(1)
with sync_playwright() as p:
    b = p.chromium.launch()
    page = b.new_page(viewport={"width": 1440, "height": 900})
    page.add_init_script(f"window.gild = {{ endpoint: async () => {json.dumps(endpoint)}, chooseFolder: async () => null, hasOwnTitleBar: false }};")
    page.goto("http://localhost:8099/")
    page.wait_for_timeout(3000)
    page.get_by_text(re.compile("checkout total", re.I)).first.click()
    page.wait_for_timeout(2500)
    page.screenshot(path=f"{root}/1-quest.png")
    page.get_by_text("Backup companions").first.click()
    page.wait_for_timeout(1000)
    page.get_by_text("+ Add a backup Companion").click()
    page.wait_for_timeout(1000)
    page.screenshot(path=f"{root}/2-backups.png")
    page.get_by_text("← Back").first.click()
    page.wait_for_timeout(1000)
    page.screenshot(path=f"{root}/3-after.png")
    print("SIDE", page.get_by_text(re.compile("Check the rounding", re.I)).count())
    page.get_by_text(re.compile("Check the rounding", re.I)).first.click()
    page.wait_for_timeout(2500)
    page.screenshot(path=f"{root}/4-sidequest.png")
    page.get_by_text("Mark as done", exact=False).last.scroll_into_view_if_needed()
    page.wait_for_timeout(500)
    page.screenshot(path=f"{root}/5-sidequest-bottom.png")
    page.get_by_text("Mark as done", exact=False).last.click()
    page.wait_for_timeout(1500)
    page.screenshot(path=f"{root}/6-sidequest-done.png")
    page.set_viewport_size({"width": 700, "height": 900})
    page.wait_for_timeout(800)
    page.screenshot(path=f"{root}/7-narrow.png")
    b.close()

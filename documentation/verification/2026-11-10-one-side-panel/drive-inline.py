import re, json
from playwright.sync_api import sync_playwright
root = "/tmp/claude-501/gild-ui"
endpoint = re.search(r"ENDPOINT (\S+)", open(f"{root}/serve.log").read()).group(1)
with sync_playwright() as p:
    b = p.chromium.launch()
    page = b.new_page(viewport={"width": 1440, "height": 1000})
    page.add_init_script(f"window.gild = {{ endpoint: async () => {json.dumps(endpoint)}, chooseFolder: async () => null, hasOwnTitleBar: false }};")
    page.goto("http://localhost:8099/")
    page.wait_for_timeout(3000)
    page.get_by_text(re.compile("checkout total", re.I)).first.click()
    page.wait_for_timeout(2500)
    page.get_by_text("Backup companions").first.click()
    page.wait_for_timeout(1500)
    page.get_by_text("+ Add a backup Companion").click()
    page.wait_for_timeout(800)
    page.get_by_text("+ Add a backup Companion").click()
    page.wait_for_timeout(1000)
    page.screenshot(path=f"{root}/8-inline.png")
    page.get_by_label("Move backup 2 up").click()
    page.wait_for_timeout(800)
    page.get_by_label("Remove backup 1").click()
    page.wait_for_timeout(1000)
    page.screenshot(path=f"{root}/9-inline-after.png")
    print("SCREENS_BACK_LINK", page.get_by_text("← Back").count())
    page.reload(); page.wait_for_timeout(3000)
    page.get_by_text(re.compile("checkout total", re.I)).first.click(); page.wait_for_timeout(2000)
    print("COUNT_AFTER_RELOAD", page.get_by_text("Backup companions").first.locator("xpath=..").inner_text())
    b.close()

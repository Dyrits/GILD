// Builds the relay Worker into one module and writes it as a string the app can upload to a user's own Cloudflare
// account. Run with `bun run bundle` in packages/relay after changing the Worker's sources; a test fails until you do.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { workerSourceHash } from "./workerSources.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const built = await Bun.build({
  entrypoints: [join(root, "src", "worker.ts")],
  external: ["cloudflare:workers"],
  format: "esm",
  minify: false,
  target: "browser",
});
const output = built.outputs[0];
if (!built.success || output === undefined) {
  console.error(built.logs.join("\n"));
  process.exit(1);
}
const bundle = await output.text();
const { compatibility_date: compatibilityDate } = JSON.parse(readFileSync(join(root, "wrangler.jsonc"), "utf8")) as {
  compatibility_date: string;
};
writeFileSync(
  join(root, "src", "workerBundle.generated.ts"),
  `// Generated by scripts/bundleWorker.ts from the Worker's sources. Do not edit: run \`bun run bundle\` in packages/relay.
export const relayWorkerSourceHash = ${JSON.stringify(workerSourceHash())};
export const relayWorkerBundle = ${JSON.stringify(bundle)};
export const relayWorkerCompatibilityDate = ${JSON.stringify(compatibilityDate)};
`,
);
console.log(`Wrote src/workerBundle.generated.ts (${bundle.length} characters).`);

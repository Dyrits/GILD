import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { modelsDevUrl, rowsOfModelsDev } from "../src/core/priceSources.ts";

// Rewrites the snapshot of the model price table shipped with Iskios (decision record 0014): run before a release with
// `bun run prices:snapshot`, then `bun run format`. The snapshot is the fallback when the public table cannot be read.

const response = await fetch(modelsDevUrl, { headers: { accept: "application/json" } });
if (!response.ok) throw new Error(`models.dev answered ${response.status}`);
const rows = rowsOfModelsDev(await response.json()).toSorted((a, b) =>
  `${a.provider}/${a.model}`.localeCompare(`${b.provider}/${b.model}`),
);
const lines = rows.map(
  (row) =>
    `  { cacheRead: ${row.cacheRead}, cacheWrite: ${row.cacheWrite}, input: ${row.input}, model: ${JSON.stringify(row.model)}, output: ${row.output}, provider: ${JSON.stringify(row.provider)} },`,
);
const file = `import type { PriceRow } from "./prices.ts";

// Generated by \`bun run prices:snapshot\` (packages/service/scripts/pricesSnapshot.ts); do not edit by hand.

/** When the snapshot was read from the public table, in milliseconds. */
export const snapshotAt = ${Date.now()};

/** The prices of the models the harnesses offer, in dollars per million tokens, as read at \`snapshotAt\`. */
export const snapshotPrices: ReadonlyArray<PriceRow> = [
${lines.join("\n")}
];
`;
writeFileSync(join(import.meta.dirname, "../src/core/priceSnapshot.ts"), file);
console.log(`${rows.length} prices written`);
